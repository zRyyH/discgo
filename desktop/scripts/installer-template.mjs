// Rebuilds src-tauri/installer/installer.nsi (PLAN fase 9B): downloads Tauri's NSIS
// template for the installed CLI version and applies the DiscGo changes. Run it after
// upgrading @tauri-apps/cli; it fails loudly if an anchor moved upstream.
//   node desktop/scripts/installer-template.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const version = createRequire(import.meta.url)('@tauri-apps/cli/package.json').version;
const url = `https://raw.githubusercontent.com/tauri-apps/tauri/tauri-cli-v${version}/crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: ${res.status}`);
let t = (await res.text()).replace(/\r\n/g, '\n');

const patch = (name, find, add) => {
  if (!t.includes(find)) throw new Error(`anchor not found upstream: ${name}`);
  t = t.replace(find, () => add(find)); // a function: no `$` patterns in the replacement
};

patch('details list', 'BrandingText "${COPYRIGHT}"\n', (s) =>
  s + '; DiscGo: no "show details" list; the page only has the mark, a line and the bar.\nShowInstDetails nevershow\n');

patch('progress page', '!insertmacro MUI_PAGE_INSTFILES\n', (s) =>
  '; DiscGo: styled by installer/discgo.nsh.\n!define MUI_PAGE_CUSTOMFUNCTION_SHOW DiscGoInstFilesShow\n' + s);

patch('one page', '  ${GetOptions} $CMDLINE "/UPDATE" $UpdateMode\n  ${IfNot} ${Errors}\n    StrCpy $UpdateMode 1\n  ${EndIf}\n', (s) =>
  s +
  [
    '',
    '  ; DiscGo: a double-click install asks nothing: it takes the passive path (no pages but',
    '  ; the progress one, reinstall over an older version) and opens the app when done.',
    '  ${IfNot} ${Silent}',
    '  ${AndIf} $PassiveMode <> 1',
    '  ${AndIf} $UpdateMode <> 1',
    '    StrCpy $PassiveMode 1',
    '    StrCpy $DiscGoOpenWhenDone 1',
    '  ${EndIf}',
    '',
  ].join('\n'));

patch('open the app', 'Function .onInstSuccess\n', (s) =>
  s +
  [
    '  ; DiscGo: open the app after a double-click install.',
    '  ${If} $DiscGoOpenWhenDone = 1',
    '    nsis_tauri_utils::RunAsUser "$INSTDIR\\${MAINBINARYNAME}.exe" ""',
    '  ${EndIf}',
    '',
  ].join('\n'));

const head = [
  `; DiscGo: Tauri ${version}'s NSIS template (crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi`,
  `; at tag tauri-cli-v${version}) with the changes marked "DiscGo" (PLAN fase 9B): a double-click`,
  '; install runs like passive mode on one styled progress page (installer/discgo.nsh) and',
  '; opens the app at the end. Generated by desktop/scripts/installer-template.mjs; run it again',
  '; after upgrading the Tauri CLI.',
  '',
].join('\n');
const out = path.join(here, '../src-tauri/installer/installer.nsi');
fs.writeFileSync(out, head + t);
console.log(`${path.relative(process.cwd(), out)} from Tauri CLI ${version}`);
