<#
.SYNOPSIS
  Copies the minimal GStreamer runtime used by discgo-engine (PLAN 6.10).

.DESCRIPTION
  Reads plugins.txt, copies those plugins and the transitive closure of their
  DLL dependencies (resolved with dumpbin against the GStreamer bin directory),
  plus the app-local MSVC runtime, into:
    <OutDir>\bin\*.dll        core libraries (must sit next to the engine exe)
    <OutDir>\plugins\*.dll    plugins (GST_PLUGIN_SYSTEM_PATH)
  and writes the resolved file list to dlls.lock.txt (versioned, so changes in
  the runtime show up in review).

  With -StageDir, also lays out a self-contained, runnable engine folder:
    <StageDir>\discgo-engine.exe, <StageDir>\*.dll, <StageDir>\resources\gst\plugins\*.dll

.EXAMPLE
  .\collect.ps1
  .\collect.ps1 -StageDir $env:TEMP\discgo-engine-stage -EngineExe ..\..\target\release\discgo-engine.exe
#>
[CmdletBinding()]
param(
  [string]$GstRoot = $env:GSTREAMER_1_0_ROOT_MSVC_X86_64,
  [string]$OutDir,
  [string]$EngineExe,
  [string]$StageDir
)
$ErrorActionPreference = 'Stop'
# Defaults live here: $PSScriptRoot is empty in param() under 'powershell -File' (5.1).
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $OutDir) { $OutDir = Join-Path $here '..\..\desktop\src-tauri\resources\gst' }
if (-not $EngineExe) { $EngineExe = Join-Path $here '..\..\target\release\discgo-engine.exe' }

if (-not $GstRoot -or -not (Test-Path $GstRoot)) {
  throw 'GStreamer not found: set GSTREAMER_1_0_ROOT_MSVC_X86_64 or pass -GstRoot'
}
$gstBin = Join-Path $GstRoot 'bin'
$gstPlugins = Join-Path $GstRoot 'lib\gstreamer-1.0'

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
$dumpbin = & $vswhere -latest -products * -find 'VC\Tools\MSVC\**\bin\Hostx64\x64\dumpbin.exe' | Select-Object -First 1
if (-not $dumpbin) { throw 'dumpbin.exe not found (install the MSVC build tools)' }
$crtDir = & $vswhere -latest -products * -find 'VC\Redist\MSVC\**\x64\Microsoft.VC*.CRT' |
  Where-Object { $_ -notmatch 'onecore|debug' } | Select-Object -First 1
if (-not $crtDir) { throw 'MSVC redistributable CRT folder not found' }

function Get-Dependents([string]$path) {
  # Both regular and delay-load imports are listed as indented "*.dll" lines.
  & $dumpbin /nologo /dependents $path |
    ForEach-Object { $_.Trim() } |
    Where-Object { $_ -match '^[\w.+-]+\.dll$' }
}

$plugins = Get-Content (Join-Path $here 'plugins.txt') |
  ForEach-Object { ($_ -replace '#.*$', '').Trim() } | Where-Object { $_ }

$binFiles = [System.Collections.Generic.SortedSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$queue = [System.Collections.Generic.Queue[string]]::new()

$pluginFiles = foreach ($p in $plugins) {
  $f = Join-Path $gstPlugins "gst$p.dll"
  if (-not (Test-Path $f)) { throw "plugin not found: $f" }
  $queue.Enqueue($f)
  $f
}
if (Test-Path $EngineExe) {
  $queue.Enqueue((Resolve-Path $EngineExe).Path)
} else {
  Write-Warning "engine not built at $EngineExe; resolving core DLLs from plugins only"
  $queue.Enqueue((Join-Path $gstBin 'gstreamer-1.0-0.dll'))
}

while ($queue.Count -gt 0) {
  foreach ($dep in Get-Dependents $queue.Dequeue()) {
    $candidate = Join-Path $gstBin $dep
    if ((Test-Path $candidate) -and $binFiles.Add($dep)) {
      $queue.Enqueue($candidate)
    }
  }
}

if (Test-Path $OutDir) { Remove-Item -Recurse -Force $OutDir }
$outBin = New-Item -ItemType Directory -Force (Join-Path $OutDir 'bin')
$outPlugins = New-Item -ItemType Directory -Force (Join-Path $OutDir 'plugins')

foreach ($f in $binFiles) { Copy-Item (Join-Path $gstBin $f) $outBin }
foreach ($f in $pluginFiles) { Copy-Item $f $outPlugins }
$crt = 'vcruntime140.dll', 'vcruntime140_1.dll', 'msvcp140.dll'
foreach ($f in $crt) { Copy-Item (Join-Path $crtDir $f) $outBin }

$lock = @('# Generated by collect.ps1 - do not edit.', '[bin]') +
  @(Get-ChildItem $outBin | Sort-Object Name | ForEach-Object Name) +
  @('[plugins]') + @(Get-ChildItem $outPlugins | Sort-Object Name | ForEach-Object Name)
$lock | Set-Content -Encoding utf8 (Join-Path $here 'dlls.lock.txt')

$size = (Get-ChildItem -Recurse -File $OutDir | Measure-Object Length -Sum).Sum / 1MB
'{0} core DLLs, {1} plugins, {2:N1} MB -> {3}' -f (Get-ChildItem $outBin).Count, $pluginFiles.Count, $size, (Resolve-Path $OutDir)

if ($StageDir) {
  if (-not (Test-Path $EngineExe)) { throw "-StageDir needs the engine exe at $EngineExe" }
  if (Test-Path $StageDir) { Remove-Item -Recurse -Force $StageDir }
  New-Item -ItemType Directory -Force (Join-Path $StageDir 'resources\gst\plugins') | Out-Null
  Copy-Item $EngineExe $StageDir
  Copy-Item (Join-Path $outBin '*') $StageDir
  Copy-Item (Join-Path $outPlugins '*') (Join-Path $StageDir 'resources\gst\plugins')
  "staged -> $(Resolve-Path $StageDir)"
}
